//! Compile the canonical JSON diagnostic bindings for the selected runtime.
use cem_ml::{
    schema::package_sources::builtin_schema_package_source,
    validation::json::JsonSchemaContractCatalog,
};
use std::{fmt::Write, fs, path::Path, process::ExitCode};

fn output() -> String {
    let source = builtin_schema_package_source("json")
        .expect("canonical JSON package")
        .schema_source;
    let contracts = JsonSchemaContractCatalog::from_schema_source(source);
    let mut code = String::from("// @generated by cem-ml-json-contracts-emit; do not edit.\n");
    writeln!(
        code,
        "const EXPECTED_SOURCE: &[u8] = {source:?}.as_bytes();"
    )
    .unwrap();
    code.push_str(r#"
pub(super) const fn source_matches(source: &[u8]) -> bool {
    if source.len() != EXPECTED_SOURCE.len() { return false; }
    let mut index = 0;
    while index < source.len() {
        if source[index] != EXPECTED_SOURCE[index] { return false; }
        index += 1;
    }
    true
}
#[cfg(all(target_arch = "wasm32", feature = "selected-application-runtime"))]
const _: () = assert!(source_matches(include_bytes!("../../../schema-packages/json/v1/schema/json.cem")),
    "stale selected JSON contracts; regenerate with cem-ml-json-contracts-emit");

pub(super) fn catalog() -> super::JsonSchemaContractCatalog {
    super::JsonSchemaContractCatalog { fact_bindings: [
"#);
    let optional = |value: &Option<String>| match value {
        Some(value) => format!("Some({value:?}.into())"),
        None => "None".into(),
    };
    for (kind, binding) in contracts.fact_bindings {
        writeln!(
            code,
            "        ({kind:?}.into(), super::JsonDiagnosticBinding {{"
        )
        .unwrap();
        writeln!(
            code,
            "            fact_kind: {:?}.into(), contract: {:?}.into(),",
            binding.fact_kind, binding.contract
        )
        .unwrap();
        writeln!(
            code,
            "            behavior: {}, diagnostic_code: {:?}.into(),",
            optional(&binding.behavior),
            binding.diagnostic_code
        )
        .unwrap();
        writeln!(
            code,
            "            severity: super::Severity::{:?}, policy: {},",
            binding.severity,
            optional(&binding.policy)
        )
        .unwrap();
        code.push_str("        }),\n");
    }
    code.push_str("    ].into_iter().collect() }\n}\n");
    code
}

fn main() -> ExitCode {
    let args: Vec<_> = std::env::args_os().skip(1).collect();
    let result = match args.as_slice() {
        [flag, path] if flag == "--out" => {
            fs::write(Path::new(path), output()).map_err(|error| error.to_string())
        }
        [flag, path] if flag == "--check" => fs::read_to_string(Path::new(path))
            .map_err(|error| error.to_string())
            .and_then(|actual| {
                if actual == output() {
                    Ok(())
                } else {
                    Err(
                        "generated JSON contracts differ from canonical source; regenerate them"
                            .into(),
                    )
                }
            }),
        _ => Err("usage: cem-ml-json-contracts-emit --out|--check <Rust file>".into()),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("cem-ml-json-contracts-emit: {error}");
            ExitCode::FAILURE
        }
    }
}
