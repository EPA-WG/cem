//! Cross-cutting source-map contract per AC-P-7 and `cem-ml-stack-design-impl.md` §2.

use crate::source::{ByteRange, SourceId};
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript-projections", derive(ts_rs::TS))]
#[serde(rename_all = "kebab-case")]
pub enum ScssOriginKind {
    Source,
    Module,
    Definition,
    CallSite,
    Interpolation,
    Expansion,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript-projections", derive(ts_rs::TS))]
#[serde(tag = "kind")]
pub enum TransformKind {
    /// An authored source boundary. Its span remains in that resource's UTF-8
    /// coordinates even when local numeric source IDs are reused by another parser.
    SourceBoundary {
        uri: String,
    },
    HtmlTokenizer,
    XmlTokenizer,
    CemTokenizer,
    EventNormalizer,
    SchemaValidation {
        schema_id: u32,
    },
    CemAstBuilder,
    Query,
    QueryStep,
    HandoffBoundary {
        child_content_type: String,
    },
    ContentTypeTransform {
        content_type: String,
    },
    InterpreterRender,
    TemplateTransform {
        function: String,
    },
    /// Host → cem-ql embedding boundary per AC-T-7. `host` is the byte
    /// range the host parser owned (whole attribute value, `{...}` AVT
    /// span, or `{$ ... }` expression-node body); the next frame the
    /// cem-ql parser pushes carries the sub-span inside that range.
    TemplateEmbedding {
        host: ByteRange,
    },
    /// A decoded expression segment mapped to the authored span in this frame.
    /// Equal byte lengths map linearly; unequal lengths (entities or normalized
    /// newlines) map to the whole authored segment. Expression coordinates are
    /// UTF-8 bytes relative to the retained, trimmed expression, never AST IDs.
    ExpressionEmbedding {
        expression: ByteRange,
    },
    ScssOrigin {
        origin_kind: ScssOriginKind,
        module_uri: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        name: Option<String>,
    },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript-projections", derive(ts_rs::TS))]
#[serde(tag = "kind", content = "ranges")]
pub enum FrameSpan {
    Single(ByteRange),
    Multi(Vec<ByteRange>),
}

/// One frame of the origin-first source-map stack. `byte_range` (via
/// `FrameSpan`) is the durable location identity; `line`/`column` are
/// projections derived on demand from a `LineIndex` and never stored here.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript-projections", derive(ts_rs::TS))]
pub struct SourceMapFrame {
    pub source_id: SourceId,
    pub span: FrameSpan,
    pub transform: TransformKind,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "typescript-projections", derive(ts_rs::TS))]
pub struct SourceMapStack {
    /// Ordered origin-first; the current frame is last (AC-P-7).
    pub frames: Vec<SourceMapFrame>,
}

impl SourceMapStack {
    /// Name a source-owned stack without replacing an existing origin boundary.
    /// This is metadata supplied by the native owner, never inferred from an ID.
    pub fn with_source_uri(mut self, uri: &str) -> Self {
        if !uri.is_empty()
            && !self
                .frames
                .iter()
                .any(|frame| matches!(frame.transform, TransformKind::SourceBoundary { .. }))
        {
            if let Some(frame) = self.frames.last() {
                self.frames.push(SourceMapFrame {
                    source_id: frame.source_id,
                    span: frame.span.clone(),
                    transform: TransformKind::SourceBoundary {
                        uri: uri.to_owned(),
                    },
                });
            }
        }
        self
    }
    pub fn push(&mut self, frame: SourceMapFrame) {
        self.frames.push(frame);
    }

    pub fn origin(&self) -> Option<&SourceMapFrame> {
        self.frames.first()
    }

    pub fn current(&self) -> Option<&SourceMapFrame> {
        self.frames.last()
    }
}

/// Indexed, retained native writer origins. Prefix maxima admit overlapping
/// spans while locating a selection without rescanning the complete document.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SourceMapIndex {
    spans: Vec<crate::interpreter::OutputSpan>,
    prefix_ends: Vec<u64>,
}

impl SourceMapIndex {
    pub fn new(mut spans: Vec<crate::interpreter::OutputSpan>) -> Self {
        spans.sort_by_key(|span| span.output_range.start);
        let mut maximum = 0;
        let prefix_ends = spans
            .iter()
            .map(|span| {
                maximum = maximum.max(span.output_range.end());
                maximum
            })
            .collect();
        Self { spans, prefix_ends }
    }

    /// Unmapped generated bytes never acquire a source merely from their offset.
    /// Keep writer token frames intact: equal lengths do not establish a
    /// character-level alignment contract between transformed representations.
    pub fn map_range(&self, range: ByteRange) -> Option<SourceMapStack> {
        let mut result = SourceMapStack::default();
        let end = range.end();
        let first = self.prefix_ends.partition_point(|end| *end <= range.start);
        let last = self
            .spans
            .partition_point(|span| span.output_range.start < end);
        for span in self.spans.get(first..last).unwrap_or_default() {
            let start = range.start.max(span.output_range.start);
            let end = end.min(span.output_range.end());
            if start >= end {
                continue;
            }
            for frame in &span.origin.frames {
                if !result.frames.contains(frame) {
                    result.frames.push(frame.clone());
                }
            }
        }
        (!result.frames.is_empty()).then_some(result)
    }
}

#[cfg(test)]
mod uri_tests {
    use super::*;

    #[test]
    fn generated_ranges_compose_origins_and_leave_synthetic_bytes_unmapped() {
        let origin = SourceMapStack {
            frames: vec![SourceMapFrame {
                source_id: SourceId(1),
                span: FrameSpan::Single(ByteRange::new(12, 8)),
                transform: TransformKind::CemAstBuilder,
            }],
        }
        .with_source_uri("studio://site/content/a.md");
        let spans = [crate::interpreter::OutputSpan {
            output_range: ByteRange::new(20, 8),
            origin,
        }];
        let mapped = SourceMapIndex::new(spans.to_vec())
            .map_range(ByteRange::new(22, 3))
            .unwrap();
        assert!(mapped
            .frames
            .iter()
            .all(|frame| frame.span == FrameSpan::Single(ByteRange::new(12, 8))));
        assert!(SourceMapIndex::new(spans.to_vec())
            .map_range(ByteRange::new(0, 20))
            .is_none());
        assert!(SourceMapIndex::new(vec![])
            .map_range(ByteRange::new(0, 1))
            .is_none());
        let mut overlay = spans[0].clone();
        overlay.output_range = ByteRange::new(0, 100);
        overlay.origin = SourceMapStack {
            frames: vec![SourceMapFrame {
                source_id: SourceId(1),
                span: FrameSpan::Single(ByteRange::new(100, 100)),
                transform: TransformKind::SourceBoundary {
                    uri: "studio://site/layouts/page.cemt".into(),
                },
            }],
        };
        let joined = SourceMapIndex::new(vec![spans[0].clone(), overlay])
            .map_range(ByteRange::new(22, 3))
            .unwrap();
        assert_eq!(joined.frames.len(), 3);
        assert_eq!(
            joined.frames[0].span,
            FrameSpan::Single(ByteRange::new(100, 100))
        );
        assert_eq!(
            joined.frames[2].span,
            FrameSpan::Single(ByteRange::new(12, 8))
        );
    }

    #[test]
    fn source_uri_boundary_preserves_coordinates_and_cannot_rebind_an_origin() {
        let frame = SourceMapFrame {
            source_id: SourceId(1),
            span: FrameSpan::Single(ByteRange::new(7, 9)),
            transform: TransformKind::CemAstBuilder,
        };
        let original = SourceMapStack {
            frames: vec![frame.clone()],
        };
        let named = original
            .clone()
            .with_source_uri("studio://project/templates/view.cemt");
        assert_eq!(named.frames[0], frame);
        assert_eq!(named.frames[1].span, frame.span);
        assert_eq!(
            named.clone().with_source_uri("studio://other/data.cem"),
            named
        );
        assert_eq!(original.clone().with_source_uri(""), original);
        assert!(SourceMapStack::default()
            .with_source_uri("memory:unknown")
            .frames
            .is_empty());
        let json = serde_json::to_vec(&named).unwrap();
        assert_eq!(
            serde_json::from_slice::<SourceMapStack>(&json).unwrap(),
            named
        );
    }
}

